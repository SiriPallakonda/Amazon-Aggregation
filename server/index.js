import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import path from 'path';
import { fileURLToPath } from 'url';
import { connectDB, isDemoMode, seedDatabase } from './db.js';
import { getDashboard, runPreset, executePipeline, getCollections, getPerformance, findMany } from './analytics.js';

const app=express();
const PORT=process.env.PORT||5000;
const __dirname=path.dirname(fileURLToPath(import.meta.url));
app.use(cors());app.use(express.json({limit:'1mb'}));
app.get('/api/health',(req,res)=>res.json({ok:true,database:isDemoMode()?'demo':'mongodb',message:isDemoMode()?'Running with built-in sample data':'Connected to MongoDB'}));
app.get('/api/dashboard',async(req,res)=>{try{res.json(await getDashboard());}catch(e){res.status(500).json({error:e.message});}});
app.get('/api/collections',async(req,res)=>{try{res.json(await getCollections());}catch(e){res.status(500).json({error:e.message});}});
app.get('/api/orders',async(req,res)=>{try{const docs=await findMany('orders');res.json(docs.slice().sort((a,b)=>b.order_id-a.order_id).slice(0,100));}catch(e){res.status(500).json({error:e.message});}});
app.get('/api/products',async(req,res)=>{try{res.json(await findMany('products'));}catch(e){res.status(500).json({error:e.message});}});
app.get('/api/customers',async(req,res)=>{try{res.json(await findMany('customers'));}catch(e){res.status(500).json({error:e.message});}});
app.get('/api/preset/:name',async(req,res)=>{try{res.json(await runPreset(req.params.name));}catch(e){res.status(400).json({error:e.message});}});
app.post('/api/aggregate',async(req,res)=>{try{res.json(await executePipeline(req.body.collection,req.body.pipeline));}catch(e){res.status(400).json({error:e.message});}});
app.get('/api/performance',async(req,res)=>{try{res.json(await getPerformance());}catch(e){res.status(500).json({error:e.message});}});
const dist=path.join(__dirname,'../client/dist');
app.use(express.static(dist));app.get('*',(req,res)=>res.sendFile(path.join(dist,'index.html')));
connectDB().then(()=>{app.listen(PORT,()=>console.log(`Amazon Analytics running on ${PORT} (${isDemoMode()?'demo':'MongoDB'})`));}).catch(err=>{console.error('MongoDB connection failed:',err.message);console.error('Set MONGODB_URI or remove it to use demo mode.');process.exit(1);});
